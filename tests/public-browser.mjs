import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { once } from 'node:events';

const dir = mkdtempSync(path.join(tmpdir(), 'qingdun-public-browser-'));
const port = 18000 + Math.floor(Math.random() * 1000);
const base = `http://127.0.0.1:${port}`;
const child = spawn(process.execPath, ['server/index.js'], { env: { ...process.env, PORT: String(port), HOST: '127.0.0.1', DATA_DIR: dir, PUBLIC_ORIGIN: '' }, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
try {
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(Error('Server startup timeout')), 10000);
    child.stdout.on('data', data => { if (String(data).includes('青盾 API')) { clearTimeout(timer); resolve(); } });
    child.once('exit', code => { clearTimeout(timer); reject(Error('Server exited ' + code)); });
  });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const a = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const b = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await a.newPage(), mobile = await b.newPage(), errors = [];
  for (const p of [page, mobile]) p.on('pageerror', e => errors.push(e.message));
  mkdirSync('artifacts', { recursive: true });
  await page.goto(base);
  await page.getByRole('button', { name: '租房合同帮我看看' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.problem-card').disabled);
  assert.equal(await page.locator('.sidebar').count(), 0);
  assert.equal(await page.locator('.public-layout').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
  assert.equal(await page.locator('.problem-card').count(), 4);
  await page.getByRole('button', { name: '还有其他兼职、实习问题？' }).click();
  assert.equal(await page.locator('.problem-card').count(), 6);
  await page.getByRole('button', { name: '收起其他情况' }).click();
  await page.getByRole('group', { name: '选择材料清单场景' }).getByRole('button', { name: '兼职', exact: true }).click();
  await page.getByRole('checkbox', { name: '招聘广告或岗位介绍' }).check();
  await page.getByRole('group', { name: '选择材料清单场景' }).getByRole('button', { name: '租房', exact: true }).click();
  await page.getByRole('checkbox', { name: '租赁合同或补充约定' }).check();
  await page.getByRole('group', { name: '选择材料清单场景' }).getByRole('button', { name: '兼职', exact: true }).click();
  assert.ok(await page.getByRole('checkbox', { name: '招聘广告或岗位介绍' }).isChecked());
  await page.getByRole('group', { name: '选择材料清单场景' }).getByRole('button', { name: '租房', exact: true }).click();
  await page.locator('.home-faq summary').filter({ hasText: '没有合同，只有聊天截图，也能用吗？' }).click();
  assert.ok(await page.getByText('可以。从招聘信息、聊天、付款凭证或照片中任选一份开始', { exact: false }).isVisible());
  await page.locator('.home-faq summary').filter({ hasText: '没有合同，只有聊天截图，也能用吗？' }).click();
  await page.screenshot({ path: 'artifacts/public-home-desktop.png', fullPage: true });
  await mobile.goto(base);
  await mobile.waitForFunction(() => !document.querySelector('.problem-card').disabled);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: 'artifacts/public-home-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '押金被扣怎么办' }).click();
  await page.getByRole('heading', { name: '先上传一份材料，或说说你的情况' }).waitFor();
  const id = page.url().split('case/')[1];
  assert.ok(id);
  assert.equal((await (await a.request.get(base + '/api/cases/' + id)).json()).stage, '已经发生问题');
  assert.equal((await b.request.get(base + '/api/cases/' + id)).status(), 404);
  await page.getByRole('button', { name: '先描述我的情况' }).click();
  await page.getByRole('tab', { name: '实际情况' }).getAttribute('aria-selected').then(v => assert.equal(v, 'true'));
  await page.getByRole('tab', { name: /^材料档案/ }).click();
  await page.locator('input[type=file]').setInputFiles({ name: '租赁合同.txt', mimeType: 'text/plain', buffer: Buffer.from('租赁合同：押金2000元。房东可随时扣除全部押金，具体标准由房东解释。') });
  await page.getByRole('button', { name: '租赁合同.txt', exact: true }).waitFor();
  await page.getByRole('tab', { name: /^事实核对/ }).click();
  await page.screenshot({ path: 'artifacts/public-first-result-desktop.png', fullPage: true });
  const data = await (await a.request.get(base + '/api/cases/' + id)).json();
  assert.equal(data.materials.length, 1);
  assert.ok(data.findings.length > 0);
  assert.equal(await page.locator('.sidebar').count(), 0);
  await page.getByRole('navigation', { name: '网站导航' }).getByRole('button', { name: '我的记录', exact: true }).click();
  await page.getByRole('heading', { name: '我的记录', exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/public-records-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '押金被扣怎么办', exact: true }).click();
  await page.getByRole('heading', { name: '押金被扣怎么办', exact: true, level: 1 }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: '押金被扣怎么办', exact: true, level: 1 }).waitFor();
  await page.locator('.brand').click();
  await page.getByRole('button', { name: '继续上次记录' }).click();
  await page.getByRole('heading', { name: '押金被扣怎么办', exact: true, level: 1 }).waitFor();
  assert.equal(page.url().split('case/')[1], id);
  assert.equal((await (await a.request.get(base + '/api/cases')).json()).length, 1);
  await mobile.getByRole('button', { name: '我的记录', exact: true }).click();
  await mobile.getByRole('heading', { name: '我的记录', exact: true }).waitFor();
  assert.ok(!(await mobile.locator('main').innerText()).includes('押金被扣怎么办'));
  assert.equal(await mobile.locator('.sidebar').count(), 0);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: 'artifacts/public-records-mobile.png', fullPage: true });
  await mobile.getByRole('button', { name: '开始新问题', exact: true }).click();
  await mobile.getByRole('group', { name: '选择材料清单场景' }).getByRole('button', { name: '实习', exact: true }).click();
  await mobile.getByLabel('目前的情况').selectOption('正在履行');
  await mobile.getByRole('button', { name: '开始实习核对' }).click();
  await mobile.getByRole('heading', { name: '实习材料核对', exact: true }).waitFor();
  const preparationId = mobile.url().split('case/')[1];
  const preparationCase = await (await b.request.get(base + '/api/cases/' + preparationId)).json();
  assert.equal(preparationCase.scene, 'internship');
  assert.equal(preparationCase.stage, '正在履行');
  await mobile.getByRole('button', { name: '开始新问题', exact: true }).click();
  await mobile.getByRole('button', { name: '租房示例', exact: true }).click();
  await mobile.getByRole('heading', { name: '梧桐公寓 · 退租押金核对', exact: true }).waitFor();
  const demoId = mobile.url().split('case/')[1];
  assert.equal((await a.request.get(base + '/api/cases/' + demoId)).status(), 404);
  await mobile.screenshot({ path: 'artifacts/public-demo-mobile.png', fullPage: true });
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile home, more scenarios, preparation checklists and stage, FAQ, resume without duplicate creation, upload/findings, persistence, visitor isolation and private demo.');
} finally {
  await browser?.close();
  if (child.exitCode === null && child.signalCode === null) { const ended = once(child, 'exit'); child.kill(); await ended; }
  rmSync(dir, { recursive: true, force: true });
}
