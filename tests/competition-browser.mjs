// Live model + UI verification using an independently created fictional case only.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:8267';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1080}});
const page=await context.newPage(), errors=[];
let id;
page.on('pageerror',e=>errors.push(e.message));
fs.mkdirSync('artifacts',{recursive:true});
const shot=name=>page.screenshot({path:'artifacts/competition-'+name+'.png',fullPage:true,animations:'disabled'});
const tab=name=>page.getByRole('tab',{name:new RegExp('^'+name)}).click();
try {
  await page.goto(origin);
  await page.getByRole('button',{name:'东盟双语案例 / Try bilingual demo'}).click();
  await page.getByRole('heading',{name:'越南留学生 · 双语租房押金核对',exact:true}).waitFor();
  id=page.url().split('case/')[1];
  await shot('overview-desktop');
  await page.getByRole('button',{name:'开始 AI 核对',exact:true}).click();
  assert.ok((await page.locator('.analysis-manifest').innerText()).includes('Rental agreement'));
  await page.getByRole('checkbox',{name:/我已核对材料范围/}).check();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/analysis')&&r.request().method()==='POST',{timeout:120000});
  await page.getByRole('button',{name:'开始核对',exact:true}).click();
  await page.locator('.analysis-progress').waitFor();
  const response=await responsePromise, data=await response.json();
  assert.ok(response.ok(),JSON.stringify(data));
  fs.writeFileSync('artifacts/competition-bilingual-model.json',JSON.stringify({dataType:'fictional demo only',...data.aiAnalysis},null,2));
  assert.ok(data.aiAnalysis.findings.length>0);
  assert.ok(data.aiAnalysis.findings.every(f=>f.titleEn&&f.descriptionEn),'Every bilingual result needs English assistance');
  assert.ok(data.aiAnalysis.findings.some(f=>f.relatedMaterialId&&f.relatedQuote),'Cross-material evidence must appear in the bilingual demonstration');
  await page.locator('.ai-result-status').waitFor();
  assert.ok(await page.locator('.finding-translation').count()>0);
  await shot('bilingual-analysis-desktop');
  fs.writeFileSync('artifacts/competition-bilingual-model.json',JSON.stringify({dataType:'fictional demo only',...data.aiAnalysis},null,2));
  const original=page.locator('.finding-card').filter({has:page.locator('.finding-translation')}).first();
  await original.getByRole('button',{name:'定位原文'}).click();
  assert.ok(await page.locator('.material-transcript mark').count()>0);
  await page.getByRole('button',{name:'关闭材料',exact:true}).click();
  await original.getByRole('button',{name:'记录为争议项目'}).click();
  await page.getByRole('button',{name:'保存项目',exact:true}).click();
  await page.getByRole('button',{name:'保存项目',exact:true}).waitFor({state:'hidden'});
  await tab('公共法律服务');
  await page.getByRole('heading',{name:'公共法律服务 / Legal service preparation',exact:true}).waitFor();
  await shot('service-desktop');
  const [briefDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'下载咨询材料 / Download brief'}).click()]);
  await briefDownload.saveAs('artifacts/competition-consultation.txt');
  const brief=fs.readFileSync('artifacts/competition-consultation.txt','utf8');
  assert.ok(brief.includes(data.aiAnalysis.findings[0].descriptionEn));
  assert.ok(brief.includes('Machine translation'));
  await tab('事项报告');
  const frame=page.frameLocator('iframe[title="事项报告预览"]');
  await frame.getByRole('heading',{name:'附录 AI辅助核对与引用校验'}).waitFor();
  assert.ok((await frame.locator('body').innerText()).includes(data.aiAnalysis.findings[0].descriptionEn));
  const report=await context.request.get(origin+'/api/cases/'+id+'/report');
  fs.writeFileSync('artifacts/competition-report.html',await report.text());
  await page.setViewportSize({width:390,height:844});
  for(const name of ['事项概览','事实核对','公共法律服务','事项报告']) {
    await tab(name);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),name+' mobile overflow');
    await shot(({事项概览:'overview',事实核对:'analysis',公共法律服务:'service',事项报告:'report'})[name]+'-mobile');
  }
  await tab('公共法律服务');
  await page.getByLabel('事项发生地 / Location of matter').selectOption('东盟国家 ASEAN country');
  await page.getByRole('button',{name:'保存服务信息 / Save intake'}).click();
  await page.getByRole('button',{name:'保存服务信息 / Save intake'}).waitFor({state:'visible'});
  await page.waitForFunction(()=>document.body.innerText.includes('服务信息已保存'));
  await tab('事实核对');
  await page.getByText('上次分析已过期，请重新核对',{exact:true}).waitFor();
  assert.equal(await page.locator('.finding-translation').count(),0);
  const staleBrief=await context.request.get(origin+'/api/cases/'+id+'/consultation');
  assert.ok(!(await staleBrief.text()).includes(data.aiAnalysis.findings[0].descriptionEn));
  const canvas=await context.newPage();
  await canvas.setContent('<html><body style="font:28px Microsoft YaHei;padding:50px;line-height:2;background:white;color:black"><h2>模拟材料 / SIMULATED</h2><p>租房押金：2000元</p><p>房东主张扣款：800元</p><p>维修凭证：待提供</p><p>本图片仅用于识别测试，不是真实凭证。</p></body></html>');
  const image=await canvas.screenshot({path:'artifacts/competition-ocr-input.png'});
  await canvas.close();
  const upload=await context.request.post(origin+'/api/cases/'+id+'/materials',{multipart:{files:{name:'simulated-ocr.png',mimeType:'image/png',buffer:image}}});
  assert.ok(upload.ok());
  const detail=await (await context.request.get(origin+'/api/cases/'+id)).json();
  const imageMaterial=detail.materials.find(m=>m.name==='simulated-ocr.png');
  assert.ok(imageMaterial);
  const ocr=await context.request.post(origin+'/api/cases/'+id+'/materials/'+imageMaterial.id+'/ocr',{data:{consent:true},timeout:120000});
  const recognized=await ocr.json();
  assert.ok(ocr.ok(),JSON.stringify(recognized));
  assert.match(recognized.text,/2000/);assert.match(recognized.text,/800/);
  fs.writeFileSync('artifacts/competition-ocr-result.txt',recognized.text);
  const afterOcr=await (await context.request.get(origin+'/api/cases/'+id)).json();
  assert.equal(afterOcr.materials.find(m=>m.id===imageMaterial.id).text,'');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({pass:true,bilingualFindings:data.aiAnalysis.findings.length,rejected:data.aiAnalysis.rejectedCount,modelDurationMs:data.aiAnalysis.durationMs,ocr:true,mobile:true,staleExclusion:true,consultationExport:true}));
} catch(e) {await shot('failure');throw e;}
finally {if(id)await context.request.delete(origin+'/api/cases/'+id);await browser.close();}
